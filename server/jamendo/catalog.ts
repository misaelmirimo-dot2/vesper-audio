export function hydrateDevTrack(
  seed: CatalogTrackSeed,
  globalDownloadsEnabled: boolean,
  commercialModeRequested: boolean
): NormalizedTrack {
  const downloadUrl = seed.audiodownloadAllowed
    ? `/api/demo-audio/${seed.providerTrackId}?download=1`
    : null;

  const evaluation = validateTrackLicense({
    audiodownloadAllowed: seed.audiodownloadAllowed,
    downloadUrl,
    licenseUrl: seed.licenseUrl,
    globalDownloadsEnabled,
    commercialModeRequested,
  });

  return {
    id: seed.providerTrackId,
    provider: 'jamendo',
    providerTrackId: seed.providerTrackId,
    title: seed.title,
    artistName: seed.artistName,
    artistId: seed.artistId,
    albumName: seed.albumName,
    albumId: seed.albumId,
    artworkUrl: seed.artworkUrl,
    duration: seed.duration,
    genre: seed.genre,
    tags: seed.tags,
    releaseDate: seed.releaseDate,
    isInstrumental: seed.isInstrumental,
    streamingUrl: `/api/demo-audio/${seed.providerTrackId}`,
    downloadUrl: evaluation.offlineDownloadPermitted ? downloadUrl : null,
    originalTrackUrl: `https://www.jamendo.com/track/${seed.providerTrackId}`,
    audiodownloadAllowed: seed.audiodownloadAllowed,
    licenseType: evaluation.licenseType,
    licenseUrl: evaluation.licenseUrl,
    licenseEvaluation: evaluation,
    sourceMode: 'development-catalog',
    audioFormat: 'audio/wav',
  };
}
